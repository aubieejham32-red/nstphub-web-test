<?php

namespace App\Mail;

use Illuminate\Bus\Queueable;
use Illuminate\Mail\Mailable;
use Illuminate\Mail\Mailables\Content;
use Illuminate\Mail\Mailables\Envelope;
use Illuminate\Queue\SerializesModels;

class InstructorCoordinatorVerificationCodeMail extends Mailable
{
    use Queueable, SerializesModels;


    /*
    |--------------------------------------------------------------------------
    | Verification Code
    |--------------------------------------------------------------------------
    */

    public string $code;


    /*
    |--------------------------------------------------------------------------
    | Account Type
    |--------------------------------------------------------------------------
    |
    | instructor
    | coordinator
    |
    */

    public string $accountType;


    /*
    |--------------------------------------------------------------------------
    | Full Name
    |--------------------------------------------------------------------------
    */

    public string $fullName;


    /*
    |--------------------------------------------------------------------------
    | NSTP Component
    |--------------------------------------------------------------------------
    |
    | CWTS
    | LTS
    | ROTC
    |
    */

    public ?string $component;


    /*
    |--------------------------------------------------------------------------
    | University Name
    |--------------------------------------------------------------------------
    */

    public ?string $universityName;


    /*
    |--------------------------------------------------------------------------
    | Create A New Message Instance
    |--------------------------------------------------------------------------
    */

    public function __construct(
        string $code,
        string $accountType,
        string $fullName,
        ?string $component = null,
        ?string $universityName = null
    ) {

        /*
        |--------------------------------------------------------------------------
        | Verification Code
        |--------------------------------------------------------------------------
        */

        $this->code =
            $code;


        /*
        |--------------------------------------------------------------------------
        | Account Type
        |--------------------------------------------------------------------------
        */

        $this->accountType =
            strtolower(
                trim(
                    $accountType
                )
            );


        /*
        |--------------------------------------------------------------------------
        | Full Name
        |--------------------------------------------------------------------------
        */

        $this->fullName =
            $fullName;


        /*
        |--------------------------------------------------------------------------
        | Component
        |--------------------------------------------------------------------------
        */

        $this->component =
            $component;


        /*
        |--------------------------------------------------------------------------
        | University
        |--------------------------------------------------------------------------
        */

        $this->universityName =
            $universityName;
    }


    /*
    |--------------------------------------------------------------------------
    | Envelope
    |--------------------------------------------------------------------------
    */

    public function envelope(): Envelope
    {
        return new Envelope(
            subject:
                'NSTP Hub Password Reset Verification Code'
        );
    }


    /*
    |--------------------------------------------------------------------------
    | Content
    |--------------------------------------------------------------------------
    */

    public function content(): Content
    {
        return new Content(
            view:
                'emails.instructor-coordinator-verification-code',

            with: [

                /*
                |--------------------------------------------------------------------------
                | Verification Code
                |--------------------------------------------------------------------------
                */

                'code' =>
                    $this->code,


                /*
                |--------------------------------------------------------------------------
                | Account Type
                |--------------------------------------------------------------------------
                */

                'accountType' =>
                    $this->accountType,


                /*
                |--------------------------------------------------------------------------
                | Full Name
                |--------------------------------------------------------------------------
                */

                'fullName' =>
                    $this->fullName,


                /*
                |--------------------------------------------------------------------------
                | Component
                |--------------------------------------------------------------------------
                */

                'component' =>
                    $this->component,


                /*
                |--------------------------------------------------------------------------
                | University
                |--------------------------------------------------------------------------
                */

                'universityName' =>
                    $this->universityName,

            ]
        );
    }


    /*
    |--------------------------------------------------------------------------
    | Attachments
    |--------------------------------------------------------------------------
    */

    public function attachments(): array
    {
        return [];
    }
}